    )

    /** 时刻表：方向 -> 站点 -> (工作日表, 休息日表)。 */
    private val tables: Map<Direction, Map<Stop, StopTables>> = buildTables()

    fun timetable(
        direction: Direction,
        stop: Stop,
        workday: Boolean,
    ): Map<Int, List<Int>>? {
        val t = tables[direction]?.get(stop) ?: return null
        return if (workday) t.workday else t.restDay
    }

    fun stopNote(direction: Direction, stop: Stop): String = when (direction) {
        Direction.NORTH -> when (stop) {
            Stop.DEPART -> "预计发车时刻"
            Stop.METRO -> "地铁站参考到站时刻（+1min）"
            Stop.TEACH -> "教学楼参考到站时刻（+4min）"
            Stop.TERMINAL -> "北区参考到站时刻（+8.5min）"
        }
        Direction.SOUTH -> when (stop) {
            Stop.DEPART -> "发车时刻"
            Stop.METRO -> "地铁站参考到站时刻（+6min）"
            Stop.TEACH -> "教学楼参考到站时刻（+4min）"
            Stop.TERMINAL -> "南区参考到站时刻（+8.5min）"
        }
    }

    fun terminalLabel(direction: Direction): String =
        if (direction == Direction.NORTH) "北区" else "南区"

    /** 当天是否按工作日表运行：周一~周五。 */
    fun isWorkday(dayOfWeekIso: Int): Boolean = dayOfWeekIso in 1..5

    /**
     * 下一班：返回今天该表里第一条不早于 [now] 的发车（到站）时刻。
     * 找不到（已收班）返回 null。
     */
    fun nextDeparture(
        direction: Direction,
        stop: Stop,
        now: LocalTime,
        workday: Boolean = true,
    ): LocalTime? {
        val table = timetable(direction, stop, workday) ?: return null
        for (hour in 7..22) {
            val minutes = table[hour] ?: continue
            for (minute in minutes) {
                val t = LocalTime.of(hour, minute)
                if (!t.isBefore(now)) return t
            }
        }
        return null
    }

    /** 当日班次总数。 */
    fun departuresOfDay(
        direction: Direction,
        stop: Stop,
        workday: Boolean = true,
    ): Int = timetable(direction, stop, workday)?.values?.sumOf { it.size } ?: 0

